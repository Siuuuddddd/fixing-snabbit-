CREATE TABLE staff_account (
    id UUID PRIMARY KEY,
    phone_e164 VARCHAR(16) NOT NULL UNIQUE,
    display_name VARCHAR(120) NOT NULL,
    role VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_staff_phone CHECK (phone_e164 ~ '^\+91[6-9][0-9]{9}$'),
    CONSTRAINT ck_staff_role CHECK (role IN ('SUPPORT_AGENT', 'OPERATIONS_MANAGER', 'ADMIN', 'FINANCE_OPERATOR')),
    CONSTRAINT ck_staff_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

